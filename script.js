const herbSelect = document.getElementById("herbSelect");
const herbDescription = document.getElementById("herbDescription");
const herbMemo = document.getElementById("herbMemo");

for (const herb in herbs) {
    const option = document.createElement("option");
    option.textContent = herb;
    herbSelect.appendChild(option);
}

const tagSelect = document.getElementById("tagSelect");

const tags = [];

for (const herb in herbs) {
    for (const selectTag of herbs[herb]["タグ"]) {
        if (!tags.includes(selectTag)) {
            tags.push(selectTag);
        }
    }
    
}

for (const tag of tags) {
    const option = document.createElement("option");
    option.textContent = tag;
    tagSelect.appendChild(option);

}

herbSelect.addEventListener("change", function() {
    const selectedHerb = herbSelect.value;
    if (selectedHerb === "") {
        herbDescription.textContent = "";
        herbMemo.textContent = "";
        return;
    }
    
    herbDescription.textContent = herbs[selectedHerb]["こんなハーブ"];
    herbMemo.textContent = herbs[selectedHerb]["メモ"]
});

const foundHerbSelect = document.getElementById("foundHerbSelect");
const foundHerbDescription = document.getElementById("foundHerbDescription");
const foundHerbMemo = document.getElementById("foundHerbMemo");
    
tagSelect.addEventListener("change", function() {
    const selectedTag = tagSelect.value;

    foundHerbSelect.innerHTML = '<option value="">ハーブを選んでください</option>';
    foundHerbDescription.textContent = "";
    foundHerbMemo.textContent = "";

    const foundHerbs = [];

    for (const herb in herbs) {
        if (herbs[herb]["タグ"].includes(selectedTag)) {
            foundHerbs.push(herb);
        }
    }

  
    for (const herb of foundHerbs) {
        const option = document.createElement("option");
        option.textContent = herb;
        foundHerbSelect.appendChild(option);
    }
        
});

foundHerbSelect.addEventListener("change", function() {
    const selectedHerb = foundHerbSelect.value;
    if (selectedHerb === "") {
        foundHerbDescription.textContent = "";
        foundHerbMemo.textContent = "";
        return;
    }

    foundHerbDescription.textContent = herbs[selectedHerb]["こんなハーブ"];
    foundHerbMemo.textContent = herbs[selectedHerb]["メモ"];
});
